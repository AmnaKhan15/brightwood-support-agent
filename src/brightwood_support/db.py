"""Database access: SQLite for tests and local runs, Postgres (with pgvector) in production.

The store's SQL is written once, with `?` placeholders and `RETURNING id`, and runs on both.
`Backend` decides where each visitor's sandbox lives:

  - SqliteBackend    every sandbox is a private in-memory database. Nothing survives a restart.
  - PostgresBackend  every sandbox is its own Postgres schema, so its orders, approvals and history
                     survive restarts and Render's free tier going to sleep. Shared tables (the
                     agent-run log used for metrics, the help-article vectors) live in `public`.

Postgres notes:
  - Every statement runs in its own short transaction with `SET LOCAL search_path`, so it is safe
    behind a transaction-mode pooler such as Neon's pooled endpoint (PgBouncer).
  - `prepare_threshold=None` turns off server-side prepared statements for the same reason.
"""
from __future__ import annotations

import hashlib
import re
import sqlite3
import threading
from contextlib import contextmanager
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Iterable, Iterator, Protocol


@dataclass
class Result:
    rows: list[dict] = field(default_factory=list)
    rowcount: int = 0

    def fetchone(self) -> dict | None:
        return self.rows[0] if self.rows else None

    def fetchall(self) -> list[dict]:
        return self.rows


class Database(Protocol):
    dialect: str

    def execute(self, sql: str, params: Iterable[Any] = ()) -> Result: ...
    def script(self, sql: str) -> None: ...
    def transaction(self) -> Iterator["Database"]: ...


def now_text() -> str:
    """The timestamp format every table uses (UTC, second precision)."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


ID_COLUMN = {
    "sqlite": "INTEGER PRIMARY KEY AUTOINCREMENT",
    "postgres": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
}


class SqliteDatabase:
    dialect = "sqlite"

    def __init__(self, path: str = ":memory:") -> None:
        self._conn = sqlite3.connect(path, check_same_thread=False, isolation_level=None)
        self._conn.row_factory = sqlite3.Row
        self._lock = threading.Lock()

    def execute(self, sql: str, params: Iterable[Any] = ()) -> Result:
        with self._lock:
            cur = self._conn.execute(sql, tuple(params))
            rows = [dict(r) for r in cur.fetchall()] if cur.description else []
            return Result(rows, cur.rowcount)

    def script(self, sql: str) -> None:
        with self._lock:
            self._conn.executescript(sql)

    @contextmanager
    def transaction(self) -> Iterator["SqliteDatabase"]:
        # In-memory SQLite has no round trips to save; statements simply run in order.
        yield self


def _to_pg(sql: str) -> str:
    return sql.replace("%", "%%").replace("?", "%s")


class PostgresDatabase:
    dialect = "postgres"

    def __init__(self, pool, schema: str = "public") -> None:
        if not re.fullmatch(r"[a-z_][a-z0-9_]{0,62}", schema):
            raise ValueError(f"bad schema name {schema!r}")
        self._pool = pool
        self.schema = schema

    def _path(self) -> str:
        return f'SET LOCAL search_path TO "{self.schema}", public'

    def execute(self, sql: str, params: Iterable[Any] = ()) -> Result:
        with self._pool.connection() as conn, conn.transaction():
            conn.execute(self._path())
            cur = conn.execute(_to_pg(sql), tuple(params))
            rows = [dict(r) for r in cur.fetchall()] if cur.description else []
            return Result(rows, cur.rowcount)

    def script(self, sql: str) -> None:
        with self.transaction() as tx:
            tx.script(sql)

    @contextmanager
    def transaction(self) -> Iterator["_Connection"]:
        """Several statements on one connection, in one transaction, with one search_path."""
        with self._pool.connection() as conn, conn.transaction():
            conn.execute(self._path())
            yield _Connection(conn)


class _Connection:
    """A Database bound to one open Postgres transaction (see PostgresDatabase.transaction)."""

    dialect = "postgres"

    def __init__(self, conn) -> None:
        self._conn = conn

    def execute(self, sql: str, params: Iterable[Any] = ()) -> Result:
        cur = self._conn.execute(_to_pg(sql), tuple(params))
        return Result([dict(r) for r in cur.fetchall()] if cur.description else [], cur.rowcount)

    def script(self, sql: str) -> None:
        self._conn.execute(sql)

    @contextmanager
    def transaction(self) -> Iterator["_Connection"]:
        yield self


class Backend(Protocol):
    persistent: bool
    main: Database

    def open_sandbox(self, sandbox_id: str, create: bool) -> Database | None: ...
    def drop_sandbox(self, sandbox_id: str) -> None: ...
    def checkpointer(self, serde): ...
    def help_store(self, embedder, semantic): ...


class SqliteBackend:
    """Everything in memory. Used by the tests and when DATABASE_URL is not set."""

    persistent = False

    def __init__(self) -> None:
        self.main = SqliteDatabase()
        self._sandboxes: dict[str, SqliteDatabase] = {}
        self._lock = threading.Lock()

    def open_sandbox(self, sandbox_id: str, create: bool) -> Database | None:
        with self._lock:
            if create:
                self._sandboxes[sandbox_id] = SqliteDatabase()
            return self._sandboxes.get(sandbox_id)

    def drop_sandbox(self, sandbox_id: str) -> None:
        with self._lock:
            self._sandboxes.pop(sandbox_id, None)

    def checkpointer(self, serde):
        from langgraph.checkpoint.memory import InMemorySaver
        return InMemorySaver(serde=serde)

    def help_store(self, embedder, semantic):
        from .rag import InMemoryStore
        return InMemoryStore(embedder, semantic)


def schema_for(sandbox_id: str) -> str:
    """A safe, fixed-length schema name. The session id itself never reaches SQL."""
    return "sb_" + hashlib.sha256(sandbox_id.encode()).hexdigest()[:24]


class PostgresBackend:
    persistent = True

    def __init__(self, url: str, min_size: int = 1, max_size: int = 8) -> None:
        from psycopg.rows import dict_row
        from psycopg_pool import ConnectionPool

        self.pool = ConnectionPool(
            url, min_size=min_size, max_size=max_size, open=True, name="brightwood",
            kwargs={"autocommit": True, "row_factory": dict_row, "prepare_threshold": None},
        )
        self.main = PostgresDatabase(self.pool)
        self.main.script("CREATE EXTENSION IF NOT EXISTS vector")

    def open_sandbox(self, sandbox_id: str, create: bool) -> Database | None:
        schema = schema_for(sandbox_id)
        if create:
            self.main.script(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE; CREATE SCHEMA "{schema}"')
        elif not self.main.execute("SELECT 1 FROM information_schema.schemata WHERE schema_name=?", (schema,)).rows:
            return None
        return PostgresDatabase(self.pool, schema)

    def drop_sandbox(self, sandbox_id: str) -> None:
        self.main.script(f'DROP SCHEMA IF EXISTS "{schema_for(sandbox_id)}" CASCADE')

    def checkpointer(self, serde):
        from langgraph.checkpoint.postgres import PostgresSaver
        saver = PostgresSaver(self.pool, serde=serde)
        saver.setup()
        return saver

    def help_store(self, embedder, semantic):
        from .rag import PgVectorStore
        return PgVectorStore(self.main, embedder, semantic)

    def close(self) -> None:
        self.pool.close()


def backend_from_env(env) -> Backend:
    url = env.get("DATABASE_URL", "")
    if url.startswith(("postgres://", "postgresql://")):
        # Serverless copies come and go: keep no idle connections and only a few per copy.
        serverless = bool(env.get("VERCEL"))
        return PostgresBackend(url, min_size=int(env.get("DB_POOL_MIN", 0 if serverless else 1)),
                               max_size=int(env.get("DB_POOL_MAX", 3 if serverless else 8)))
    return SqliteBackend()
